#!/usr/bin/env python3
"""Generate the vector table pieces that the PAC cannot provide.

`swm341-pac` is generated from an SVD that stops at IRQ 28, yet the silicon has
89 vectors. Because the PAC already defines `__INTERRUPTS` (a `[Vector; 29]`
array) behind its `rt` feature, this HAL neither enables that feature nor uses
the PAC's `device.x`; instead it ships its own pair:

* `device.x` -- `PROVIDE(<name> = DefaultHandler)` for all 89 vectors, which is
  what turns a Rust `#[interrupt] fn <name>()` into a real vector entry;
* `src/vector_table.rs` -- the `__INTERRUPTS` array itself, which must otherwise
  come from the device crate.

Usage:
    python3 scripts/gen_vector_table.py
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]

# Taken from `CSL/CMSIS/DeviceSupport/SWM341.h` (IRQn enum). Order matters.
VECTORS = """
UART0 UART1 TIMR0 TIMR1 DMA SPI0 PWM0 WDT UART2 PWM1 ADC0 BTIMR0 HALL0 PWM2
PWMBRK I2C0 CAN0 SPI1 RTC PWM3 TIMR2 UART3 TIMR3 ADC1 BOD CORDIC BTIMR1 PWM4
HALL3 BTIMR2 I2C1 BTIMR3 ACMP XTALSTOP FSPI GPIOA GPIOB GPIOC GPIOD GPIOM GPION
GPIOA0 GPIOA1 GPIOA5 GPIOA6 GPIOA10 GPIOA11 GPIOA12 GPIOA13 GPIOB0 GPIOB1 GPIOB2
GPIOC0 GPIOC1 GPIOC2 GPIOC3 GPIOC4 GPIOD3 GPIOD4 GPIOD5 GPIOD6 GPIOD7 GPIOD8
GPIOC9 GPIOC10 GPIOC11 GPIOC12 GPIOM0 GPIOM1 GPIOM2 GPIOM3 GPIOM4 DIV LCD GPIOE
JPEG SDIO USB CAN1 TIMR4 BTIMR4 BTIMR5 BTIMR6 BTIMR7 BTIMR8 BTIMR9 BTIMR10
BTIMR11 DMA2D
""".split()

DEVICE_X = """/* Weak aliases for every NVIC interrupt vector of the SWM341.
 *
 * This file is intentionally not taken from the `swm341-pac` crate: the SVD that
 * crate is generated from only describes the vectors 0..=28, so anything above
 * -- including the GPIO port interrupts (GPIOA = 35, GPIOB = 36, ...) -- would
 * have no vector slot to be claimed by a Rust handler.
 *
 * Generated by `scripts/gen_vector_table.py`; names follow the vendor header
 * `CSL/CMSIS/DeviceSupport/SWM341.h`, which the datasheet also uses.
 */
"""

RUST_HEADER = """//! Device specific portion of the vector table.
//!
//! Generated by `scripts/gen_vector_table.py` -- do not edit by hand.
//!
//! `cortex-m-rt` expects the device crate to expose `__INTERRUPTS` in the
//! `.vector_table.interrupts` section and expects `device.x` to carry a weak
//! alias per entry. The `swm341-pac` SVD only knows 29 of the 89 vectors this
//! chip implements, so this crate supplies both artifacts itself and leaves the
//! PAC's `rt` feature off to avoid a second, conflicting `__INTERRUPTS`.
//!
//! Every slot therefore resolves to whatever `#[interrupt] fn <name>()` exists,
//! falling back to `DefaultHandler` thanks to those weak aliases.

/// Entries of the interrupt portion of the vector table.
///
/// `cortex_m_rt::Vector` keeps its fields private, so -- exactly like the code
/// `svd2rust` generates for a PAC -- the union is declared here.
pub union Vector {
    pub handler: unsafe extern "C" fn(),
    pub reserved: u32,
}

unsafe extern "C" {
"""

RUST_TAIL = """}

#[link_section = ".vector_table.interrupts"]
#[no_mangle]
#[used]
pub static __INTERRUPTS: [Vector; COUNT] = [
ENTRIES
];
"""


def main():
    assert len(VECTORS) == 89, len(VECTORS)
    assert len(set(VECTORS)) == 89, "duplicate vector name"

    (ROOT / "device.x").write_text(
        DEVICE_X + "\n".join(f"PROVIDE({name} = DefaultHandler);" for name in VECTORS) + "\n"
    )

    entries = "\n".join(f"    Vector {{ handler: {name} }}," for name in VECTORS)
    body = RUST_HEADER + "\n".join(f"    fn {name}();" for name in VECTORS) + "\n" + RUST_TAIL
    (ROOT / "src" / "vector_table.rs").write_text(
        body.replace("COUNT", str(len(VECTORS))).replace("ENTRIES", entries)
    )
    print(f"generated device.x and src/vector_table.rs for {len(VECTORS)} vectors")


if __name__ == "__main__":
    main()
