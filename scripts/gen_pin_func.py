#!/usr/bin/env python3
"""Generate per-peripheral `pins.rs` from the vendor pin-mux header.

On the SWM341 every pin carries a 4-bit function selector whose meaning is
per pin (`0` = generic GPIO, `1` = whatever the mux maps on that pad, ...).
The authoritative list lives in the C header `SWM341_port.h`; transcribing it
by hand is exactly the kind of table where a single typo silently breaks a
peripheral, so the Rust side is generated instead.

Unlike the previous single `gpio/pins.rs`, the table is now sunk into each
peripheral's own `pins.rs` -- mirroring the `usart`/`spi` layout of the
reference py32f030 HAL. Each peripheral only sees the pads it can actually
drive; the type-checked binding (`PinFuncOf<P>`) stays in `gpio` and is
implemented here for the relevant pads.

Usage:
    python3 scripts/gen_pin_func.py <path/to/SWM341_port.h> <path/to/src>

Writes:
    src/gpio/pin_defs.rs   one `Pin` impl per pad singleton (unchanged)
    src/uart/pins.rs       UART pad functions
    src/spi/pins.rs        SPI pad functions
    src/i2c/pins.rs        I2C pad functions
    src/sdramc/pins.rs     SDRAM pad functions
"""

import re
import sys
import os
from collections import OrderedDict

DEFINE = re.compile(
    r"^#define\s+PORT(?P<port>[A-Z])_PIN(?P<pin>\d+)_(?P<name>[A-Z0-9_]+)\s+(?P<value>\d+)\s*$"
)

# Which peripheral a define belongs to, by the token it carries. Token spellings
# are taken verbatim from `SWM341_port.h`:
#   UART/SPI/I2C  -> `UART1_TX`, `SPI0_SCLK`, `I2C0_SCL` (FSPI is excluded from
#                    SPI because `FSPI_SCLK` has no digit right after `SPI`).
#   TIMR          -> `TIMR0_IN` / `TIMR0_OUT` (a word boundary before `TIMR`
#                    keeps `BTIMR0_OUT` from matching).
#   PWM           -> `PWM0A` / `PWM0B` / `PWM0AN` / `PWM0BN` (channel outputs) plus
#                    `PWM_BRK0` / `PWM_CLK0` (break / clock inputs).
#   ADC           -> `ADC0_CH0` (analog input) / `ADC0_TRIG0` (trigger input).
PERIPHERALS = OrderedDict(
    uart=re.compile(r"UART\d"),
    spi=re.compile(r"SPI\d"),
    i2c=re.compile(r"I2C\d"),
    timr=re.compile(r"\bTIMR\d_(?:IN|OUT)"),
    pwm=re.compile(r"PWM\d[ABN]{1,2}|PWM_BRK\d|PWM_CLK\d"),
    adc=re.compile(r"ADC\d_CH\d+|ADC\d_TRIG\d"),
    dac=re.compile(r"DAC_OUT|DAC\d_TRIG\d"),
    # Comparator. Spelled `ACMP\d_INP` (positive) / `ACMP\d_INN` (negative) in
    # the vendor header, so the token carries `ACMP`, not `CMP`.
    cmp=re.compile(r"ACMP\d_(?:INP|INN)"),
    # SDRAM. The vendor header spells every signal `SDR_*` (`SDR_CLK`,
    # `SDR_D0`, `SDR_BA0`, ...); the bus is spread over banks B/C/E/M/N, with
    # `SDR_LDQM`/`SDR_UDQM` also available on PA5/PD10.
    sdramc=re.compile(r"SDR_"),
)

