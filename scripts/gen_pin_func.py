def camel(symbol):
    """`HALL3_IN2` -> `Hall3In2`, keeping digit groups glued to their part."""
    return "".join(part[0].upper() + part[1:].lower() for part in symbol.split("_") if part)


def parse(path):
    """Return {(port, pin): [(value, raw_name, camel_name)]} from the header."""
    table = {}
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        for raw in handle:
            match = DEFINE.match(raw.strip())
            if match is None:
                continue
            key = (match["port"], int(match["pin"]))
            table.setdefault(key, []).append(
                (int(match["value"]), match["name"], camel(match["name"]))
            )
    return table


def classify(name):
    """Return the peripheral key (`uart`/`spi`/`i2c`) a define name drives."""
    for periph, token in PERIPHERALS.items():
        if token.search(name):
            return periph
    return None


def emit_peripheral(periph, table, out_path):
    """Write the `pins.rs` for one peripheral, filtered to its pad functions.

    The repetitive per-pin enum + `PinFunc`/`PinFuncOf` boilerplate is collapsed
    into a single `pad_funcs!` macro; each bank module then just lists its pads
    as `PinType => Enum { Variant = func_code, ... }` data.
    """
    by_port = {}
    for (port, pin), variants in table.items():
        matches = [v for v in variants if classify(v[1]) == periph]
        if matches:
            by_port.setdefault(port, {})[pin] = sorted(matches, key=lambda v: v[0])

    lines = [BANNERS[periph]]
    lines.extend(
        [
            "/// Generate the per-pin `Pin{n}Func` enums for one bank module.",
            "///",
            "/// Each entry is `PinType => Enum { Variant = func_code, ... }`; the macro",
            "/// writes the `#[repr(u8)]` enum plus its `PinFunc` / `PinFuncOf` impls.",
            "macro_rules! pad_funcs {",
            "    ( $( $pin_ty:ident => $enum:ident { $( $var:ident = $val:literal ),* $(,)? } ),* $(,)? ) => {",
            "        $(",
            "            #[derive(Clone, Copy, PartialEq, Eq, Debug)]",
            "            #[repr(u8)]",
            "            pub enum $enum {",
            "                $( $var = $val ),*",
            "            }",
            "            impl crate::gpio::PinFunc for $enum {",
            "                #[inline]",
            "                fn value(self) -> u8 { self as u8 }",
            "            }",
            "            impl crate::gpio::PinFuncOf<crate::gpio::$pin_ty> for $enum {}",
            "        )*",
            "    };",
            "}",
            "",
        ]
    )

    for port in sorted(by_port):
        lines.append(f"pub mod {port.lower()} {{")
        lines.append("    pad_funcs! {")
        for pin in sorted(by_port[port]):
            matches = by_port[port][pin]
            variants = ", ".join(f"{cam} = {value}" for (value, _raw, cam) in matches)
            lines.append(f"        P{port}{pin} => Pin{pin}Func {{ {variants} }},")
        lines.extend(["    }", "}", ""])

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines).rstrip() + "\n")


def pin_defs(table):
    """One `impl_singleton_pin!` per pad, ordered like the peripheral list."""
    lines = [
        "//! Pin singletons bound to the pad they stand for.",
        "//!",
        "//! Generated by `scripts/gen_pin_func.py` -- do not edit by hand.",
        "",
    ]
    for port in sorted({p for p, _ in table}):
        for pin in range(16):
            lines.append(f"impl_singleton_pin!(Port{port}, {port}, P{port}{pin}, {pin});")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    header, src = sys.argv[1], sys.argv[2]

    table = parse(header)
    if not table:
        sys.exit("error: no `PORTx_PINn_NAME` definitions found -- wrong header?")

    for periph in PERIPHERALS:
        out = os.path.join(src, periph, "pins.rs")
        emit_peripheral(periph, table, out)
        print(f"wrote {out}")

    with open(os.path.join(src, "gpio", "pin_defs.rs"), "w", encoding="utf-8") as handle:
        handle.write(pin_defs(table) + "\n")
    print("wrote src/gpio/pin_defs.rs")


if __name__ == "__main__":
    main()
